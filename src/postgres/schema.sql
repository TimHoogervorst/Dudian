CREATE FUNCTION record_milestone_pass() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status='passed' THEN
    INSERT INTO milestone_passes(account_id,level) VALUES(NEW.account_id,NEW.level) ON CONFLICT DO NOTHING;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER record_milestone_pass AFTER INSERT OR UPDATE OF status ON milestone_tests FOR EACH ROW EXECUTE FUNCTION record_milestone_pass();
