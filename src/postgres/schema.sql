CREATE TABLE accounts (
  id uuid PRIMARY KEY,
  username text NOT NULL,
  password_hash text NOT NULL
);
CREATE UNIQUE INDEX accounts_username ON accounts (lower(username));
CREATE TABLE sessions (
  token_hash text PRIMARY KEY, account_id uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);

CREATE TABLE stories (id text PRIMARY KEY, title text NOT NULL, content jsonb NOT NULL, created_at bigint NOT NULL);
CREATE TABLE story_levels (id text PRIMARY KEY REFERENCES stories(id), counts jsonb, level integer);
CREATE TABLE story_art (id text PRIMARY KEY REFERENCES stories(id), status text NOT NULL, image bytea, error text);
CREATE TABLE art_settings (id integer PRIMARY KEY, enabled integer, key text, portrait bytea);
CREATE TABLE art_provider (id integer PRIMARY KEY, provider text NOT NULL);
CREATE TABLE cover_models (id integer PRIMARY KEY, "apiModel" text NOT NULL, "codexModel" text NOT NULL);
CREATE TABLE flashcard_examples (text text PRIMARY KEY, before_text text NOT NULL, after_text text NOT NULL);

CREATE TABLE positions (
  account_id uuid NOT NULL REFERENCES accounts(id),
  story_id text REFERENCES stories(id),
  chapter integer NOT NULL,
  paragraph integer NOT NULL, updated_at bigint NOT NULL,
  PRIMARY KEY (account_id, story_id)
);

